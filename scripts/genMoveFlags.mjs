// Generates src/lib/moveFlags.js from @smogon/calc's Gen 9 move data (run once; output is committed).
// The damage engine needs the same per-move facts the reference calculator uses: contact / sound / punch / bite /
// pulse / slicing / bullet / wind, recoil or crash damage, secondary effects (Sheer Force), priority.
import { Generations } from '@smogon/calc'
import { writeFileSync } from 'node:fs'
import { slugify } from '../src/lib/showdownparser.js'
const gen = Generations.get(9)
const out = {}
for (const m of gen.moves) {
  if (m.isMax || m.isZ || m.name.startsWith('Max ') || m.name.startsWith('G-Max')) continue
  const f = m.flags ?? {}
  let bits = ''
  if (f.contact) bits += 'c'
  if (f.sound) bits += 's'
  if (f.punch) bits += 'p'
  if (f.bite) bits += 'b'
  if (f.pulse) bits += 'u'
  if (f.slicing) bits += 'l'
  if (f.bullet) bits += 'a'
  if (f.wind) bits += 'w'
  if (m.recoil || m.hasCrashDamage) bits += 'r'
  if (m.secondaries || m.name === 'Electro Shot' || m.name === 'Order Up') bits += 'x'
  if (m.drain) bits += 'd'
  if (m.priority > 0) bits += 'P'
  if (m.target === 'allAdjacent' || m.target === 'allAdjacentFoes') bits += 'S'
  if (bits) out[slugify(m.name)] = bits
}
const text = `// Per-move facts used by the damage engine, taken from @smogon/calc (Gen 9). Generated by scripts/genMoveFlags.mjs.
// Letters: c contact, s sound, p punch, b bite, u pulse, l slicing, a bullet, w wind, r recoil / crash damage,
// x secondary effect (Sheer Force), d drains HP, P positive priority, S spread (hits every adjacent / every adjacent foe). Moves not listed have none of these.
export const MOVE_FLAG_BITS = ${JSON.stringify(out)}
const parsed = new Map()
export function moveFlags(slug) {
  let f = parsed.get(slug)
  if (!f) {
    const b = MOVE_FLAG_BITS[slug] ?? ''
    f = { contact: b.includes('c'), sound: b.includes('s'), punch: b.includes('p'), bite: b.includes('b'), pulse: b.includes('u'), slicing: b.includes('l'),
      bullet: b.includes('a'), wind: b.includes('w'), recoil: b.includes('r'), secondary: b.includes('x'), drain: b.includes('d'), priority: b.includes('P'), spread: b.includes('S') }
    parsed.set(slug, f)
  }
  return f
}
`
writeFileSync('src/lib/moveFlags.js', text)
console.log(Object.keys(out).length, 'moves with flags')
