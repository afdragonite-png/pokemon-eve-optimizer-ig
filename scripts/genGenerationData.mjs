// Generates src/data/gen<N>.js (moves, species, type chart, items, abilities as the reference calc knows them for that
// generation). Run: node scripts/genGenerationData.mjs 8 7 6 ...   The output is committed; the app never imports the calc.
import { Generations } from '@smogon/calc'
import { writeFileSync, mkdirSync } from 'node:fs'
import { slugify } from '../src/lib/showdownparser.js'
import { EXCLUDED_MOVE_NAMES } from './excludedMoves.mjs'

// Before Gen 4 the category comes from the move's type (the calc does the same in its Move class).
const SPECIAL_TYPES = ['Fire', 'Water', 'Grass', 'Electric', 'Ice', 'Psychic', 'Dark', 'Dragon']
mkdirSync('src/data', { recursive: true })
for (const n of process.argv.slice(2).map(Number)) {
  const gen = Generations.get(n)
  const moves = {}
  for (const m of gen.moves) {
    if (EXCLUDED_MOVE_NAMES.has(m.name)) continue
    // [type, basePower, category, hasSecondary]
    moves[slugify(m.name)] = [(gen.num <= 4 && /^(Future Sight|Doom Desire)$/.test(m.name)) ? '???' : m.type.toLowerCase(), m.basePower ?? 0, (m.category ?? (gen.num < 4 ? (SPECIAL_TYPES.includes(m.type) ? 'Special' : 'Physical') : 'Status')).toLowerCase(), m.secondaries ? 1 : 0, m.target === 'allAdjacent' ? 'a' : m.target === 'allAdjacentFoes' ? 'f' : '']
  }
  const species = {}
  for (const s of gen.species) {
    if (!s.baseStats) continue
    const b = s.baseStats
    species[slugify(s.name)] = {
      t: s.types.map(t => t.toLowerCase()),
      b: n === 1 ? [b.hp, b.atk, b.def, b.spa ?? b.spc, b.spd ?? b.spc, b.spe] : [b.hp, b.atk, b.def, b.spa, b.spd, b.spe],
      a: Object.values(s.abilities ?? {}).filter(Boolean).map(slugify),
      w: s.weightkg ?? 50, g: s.gender ?? '', n: s.nfe ? 1 : 0
    }
  }
  const names = [...gen.types].map(t => t.name).filter(t => t !== '???' && t !== 'Stellar')
  const chart = {}
  for (const atk of names) {
    chart[atk.toLowerCase()] = {}
    const eff = gen.types.get(atk.toLowerCase()).effectiveness
    for (const def of names) chart[atk.toLowerCase()][def.toLowerCase()] = eff[def]
  }
  const ng = {}
  for (const it of gen.items) if (it.naturalGift) ng[slugify(it.name)] = [it.naturalGift.type.toLowerCase(), it.naturalGift.basePower]
  const data = { gen: n, ng, moves, species, chart, items: [...gen.items].map(i => slugify(i.name)), abilities: [...gen.abilities].map(a => slugify(a.name)) }
  writeFileSync(`src/data/gen${n}.js`, `// Gen ${n} data generated by scripts/genGenerationData.mjs from @smogon/calc. Do not edit by hand.\nexport default ${JSON.stringify(data)}\n`)
  console.log(`gen ${n}: ${Object.keys(moves).length} moves, ${Object.keys(species).length} species, ${data.items.length} items, ${data.abilities.length} abilities`)
}
