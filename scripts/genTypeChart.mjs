// Generates src/lib/typeChart.js from @smogon/calc's Gen 9 type data (run once; output is committed).
import { Generations } from '@smogon/calc'
import { writeFileSync } from 'node:fs'
const gen = Generations.get(9)
const names = [...gen.types].map(t => t.name).filter(n => n !== '???' && n !== 'Stellar')
const chart = {}
for (const atk of names) {
  chart[atk.toLowerCase()] = {}
  const eff = gen.types.get(atk.toLowerCase()).effectiveness
  for (const def of names) chart[atk.toLowerCase()][def.toLowerCase()] = eff[def]
}
const out = `// Gen 9 type effectiveness: TYPE_CHART[attackingType][defendingType] = 0 | 0.5 | 1 | 2.
// Generated by scripts/genTypeChart.mjs from @smogon/calc. Used as an offline fallback for PokeAPI and as test input.
export const TYPE_CHART = ${JSON.stringify(chart)}

// The chart in force: Gen 9's, unless an older generation has been activated (see generation.js).
let activeChart = TYPE_CHART
export function setActiveTypeChart(chart) { activeChart = chart ?? TYPE_CHART }
export function activeTypeChart() { return activeChart }

export function staticTypeMultiplier(moveTypeName, defenderTypeNames = []) {
  if (!moveTypeName) return 1
  const row = activeChart[moveTypeName]
  if (!row) return 1
  let m = 1
  for (const t of defenderTypeNames) m *= row[t] ?? 1
  return m
}
`
writeFileSync('src/lib/typeChart.js', out)
console.log(names.length, 'types')
